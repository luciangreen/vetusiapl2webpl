/** <module> web_support — Stage 11: Helper Predicate Library

 * A self-contained runtime support library for SWI-Prolog web programs
 * generated by the vetusiapl2webpl converter.
 *
 * This module consolidates every helper predicate that generated programs
 * may call at run time.  It is Prolog-only and carries no external
 * dependencies beyond the SWI-Prolog standard library.
 *
 * Generated programs may either:
 *   a) load this module with :- use_module(web_support). so that helpers
 *      are resolved at load time, or
 *   b) rely on the inlined versions written by emit_html_helpers/1 (from
 *      html_output.pl) when the generated file must be fully self-contained
 *      and deployed without this library present.
 *
 * Helper categories
 * -----------------
 *
 * 1. HTML fragment detection
 *      looks_like_html/1         — true when an atom appears to contain HTML
 *
 * 2. HTML escaping
 *      html_escape/2             — replace &, <, >, " with entity equivalents
 *
 * 3. Page structure
 *      html_page_header/1        — emit Content-type header + page open
 *      html_page_footer/0        — emit page close
 *
 * 4. Output helpers
 *      html_writeln/1            — emit text as <p> or pass-through HTML
 *      html_write/1              — emit text as <span> or pass-through HTML
 *      html_br/0                 — emit a <br/> line break
 *      html_safe_writeln/1       — HTML-escape then emit as <p>
 *      html_safe_write/1         — HTML-escape then emit inline
 *
 * 5. State serialisation
 *      state_serialise/2         — Prolog term → atom (for hidden fields)
 *      state_deserialise/2       — atom → Prolog term (with fallback)
 *
 * 6. Request data extraction
 *      ws_request_param/3        — extract one named parameter from a request
 *      ws_request_params/2       — extract multiple parameters at once
 *
 * 7. Raw-HTML form output
 *      ws_form_open/2            — write opening <form> tag
 *      ws_form_close/0           — write closing </form> tag
 *      ws_text_input/1           — write a text <input> element
 *      ws_password_input/1       — write a password <input> element
 *      ws_textarea_input/1       — write a <textarea> element
 *      ws_hidden_input/2         — write a hidden <input> element
 *      ws_submit/1               — write a submit <input> element
 *
 * @author  Lucian Green
 * @license BSD-3-Clause
 */

:- use_module(library(http/html_write)).

:- use_module(library(lists)).
:- use_module(library(http/http_parameters)).

% ==========================================================================
% 1. HTML fragment detection
% ==========================================================================

%% looks_like_html(+Text:atom) is semidet.
%
%  True when Text is an atom that appears to contain HTML markup, i.e. it
%  contains at least one '<' and at least one '>'.
%
%  Examples:
%    looks_like_html('<p>Hello</p>') → true
%    looks_like_html('Enter name:')  → false
looks_like_html(Text) :-
    atom(Text),
    sub_atom(Text, _, _, _, '<'),
    sub_atom(Text, _, _, _, '>').

% ==========================================================================
% 2. HTML escaping
% ==========================================================================

%% html_escape(+In, -Out) is det.
%
%  Replace HTML special characters in In with their entity equivalents:
%    &  →  &amp;   (replaced first to avoid double-escaping)
%    <  →  &lt;
%    >  →  &gt;
%    "  →  &quot;
%
%  In may be an atom or a string; Out is always an atom.
%
%  Examples:
%    html_escape('a<b', 'a&lt;b')
%    html_escape('say "hi"', 'say &quot;hi&quot;')
html_escape(In, Out) :-
    ( atom(In) -> A = In ; atom_string(A, In) ),
    atomic_list_concat(Parts0, '&',  A),
    atomic_list_concat(Parts0, '&amp;', S1),
    atomic_list_concat(Parts1, '<',  S1),
    atomic_list_concat(Parts1, '&lt;',  S2),
    atomic_list_concat(Parts2, '>',  S2),
    atomic_list_concat(Parts2, '&gt;',  S3),
    atomic_list_concat(Parts3, '"',  S3),
    atomic_list_concat(Parts3, '&quot;', Out).

% ==========================================================================
% 3. Page structure
% ==========================================================================

%% html_page_header(+Title) is det.
%
%  Write an HTTP Content-type header followed by an opening HTML page with
%  the given Title in the <title> element.
%
%  Title may be an atom or a string; it is written with ~w.
%
%  Output:
%    Content-type: text/html\n\n
%    <html>\n<head><title>Title</title></head>\n<body>\n
html_page_header(Title) :-
    format('Content-type: text/html\n\n'),
    format('<html>\n<head><title>~w</title></head>\n<body>\n', [Title]).

%% html_page_footer is det.
%
%  Write the closing HTML tags for a page.
%
%  Output:
%    </body>\n</html>\n
html_page_footer :-
    format('</body>\n</html>\n').

% ==========================================================================
% 4. Output helpers
% ==========================================================================

%% html_writeln(+Text) is det.
%
%  Write Text to current_output as an HTML paragraph, or pass it through
%  unchanged when Text is an atom that looks like HTML markup.
%
%  Plain text:    format('<p>~w</p>~n', [Text])
%  HTML fragment: format('~w~n', [Text])
html_writeln(Text) :-
    ( looks_like_html(Text) ->
        format('~w~n', [Text])
    ;   format('<p>~w</p>~n', [Text])
    ).

%% html_write(+Text) is det.
%
%  Write Text to current_output as an inline <span>, or pass it through
%  unchanged when Text is an atom that looks like HTML markup.
%
%  Plain text:    format('<span>~w</span>', [Text])
%  HTML fragment: format('~w', [Text])
html_write(Text) :-
    ( looks_like_html(Text) ->
        format('~w', [Text])
    ;   format('<span>~w</span>', [Text])
    ).

%% html_br is det.
%
%  Write a self-closing <br/> line-break element followed by a newline.
html_br :-
    format('<br/>~n').

%% html_safe_writeln(+Text) is det.
%
%  HTML-escape Text (replacing &, <, >, " with entity equivalents) and
%  write the result wrapped in a <p> paragraph element.
%
%  Example:
%    html_safe_writeln('<script>') → <p>&lt;script&gt;</p>
html_safe_writeln(Text) :-
    html_escape(Text, Escaped),
    format('<p>~w</p>~n', [Escaped]).

%% html_safe_write(+Text) is det.
%
%  HTML-escape Text and write the result inline (no wrapper element).
%
%  Example:
%    html_safe_write('a&b') → &amp;
html_safe_write(Text) :-
    html_escape(Text, Escaped),
    format('~w', [Escaped]).

% ==========================================================================
% 5. State (de)serialisation
% ==========================================================================

%% html_format(+Fmt, +Args)// is det.
%
%  format/2 output as raw HTML inside an html//1 term (reply_html_page/2).
html_format(Fmt, Args) -->
    { format(atom(A), Fmt, Args) },
    html(\[A]).

%% state_serialise(+Term, -Atom) is det.
%
%  Serialise any ground Prolog term to a canonical atom representation
%  using term_to_atom/2.  The resulting atom is safe to use as an HTML
%  form hidden-field value (the HTTP library URL-encodes/decodes it
%  transparently; html_write escapes any embedded HTML special chars).
%
%  Round-trip guarantee:
%    state_serialise(T, A), state_deserialise(A, T2)  ⇒  T2 == T
%
%  Works for: atoms, integers, floats, SWI strings, lists, compound terms.
state_serialise(Term, Atom) :-
    term_to_atom(Term, Atom).

%% state_deserialise(+Atom, -Term) is det.
%
%  Parse a previously serialised atom back to its original Prolog term.
%
%  Success cases:
%    • Atom is a valid Prolog term string  →  Term is the parsed value.
%
%  Fallback (always succeeds):
%    • Atom is not a valid Prolog term  →  Term = Atom (identity).
%
%  The fallback preserves arbitrary user-typed text (e.g. "Hello World")
%  that passes through http_parameters as-is without requiring the user to
%  type quoted Prolog syntax.
state_deserialise(Atom, Term) :-
    ( catch(term_to_atom(Term, Atom), _, fail) ->
        true
    ;   Term = Atom
    ).

% ==========================================================================
% 6. Request data extraction
% ==========================================================================

%% ws_request_param(+Request, +Name:atom, -Value) is det.
%
%  Extract a single named parameter from an HTTP request using
%  http_parameters/2.  Value is unified with the atom value of the
%  parameter.
%
%  Request — the SWI-Prolog HTTP request term passed to a handler
%  Name    — the form field name (atom)
%  Value   — the field value (atom)
%
%  Example:
%    ws_request_param(Request, 'Name', Name)
%    % equivalent to: http_parameters(Request, ['Name'(Name, [atom])])
ws_request_param(Request, Name, Value) :-
    Spec =.. [Name, Value, [atom]],
    http_parameters(Request, [Spec]).

%% ws_request_params(+Request, +Specs:list) is det.
%
%  Extract multiple named parameters from an HTTP request in one call.
%  Specs is a list of Name=Variable pairs; each variable is unified with
%  the atom value of the corresponding form field.
%
%  Request — the SWI-Prolog HTTP request term
%  Specs   — list of Name=Variable pairs, e.g. ['Name'=Name, 'Age'=Age]
%
%  Example:
%    ws_request_params(Request, ['Name'=Name, 'Age'=Age])
ws_request_params(Request, Specs) :-
    maplist(ws_build_param_term, Specs, ParamTerms),
    http_parameters(Request, ParamTerms).

%% ws_build_param_term(+Spec, -ParamTerm) is det.
%
%  Convert a Name=Variable pair into a http_parameters/2 spec term.
ws_build_param_term(Name=Value, ParamTerm) :-
    ParamTerm =.. [Name, Value, [atom]].

% ==========================================================================
% 7. Raw-HTML form output
% ==========================================================================
%
% These predicates write form HTML directly to current_output using
% format/1-2.  They are useful in result-page handlers and in programs
% that do not use reply_html_page/2.

%% ws_form_open(+Action:atom, +Method:atom) is det.
%
%  Write the opening <form> tag with the given action URL and method.
%  Method should be 'get' or 'post'.
%
%  Example:
%    ws_form_open('/step_1', post)
%    → <form action="/step_1" method="post">
ws_form_open(Action, Method) :-
    format('<form action="~w" method="~w">~n', [Action, Method]).

%% ws_form_close is det.
%
%  Write the closing </form> tag.
ws_form_close :-
    format('</form>~n').

%% ws_text_input(+Name:atom) is det.
%
%  Write a text input element with the given field name.
%
%  Output:  <input type="text" name="Name" autofocus/>
ws_text_input(Name) :-
    format('<input type="text" name="~w" autofocus/>~n', [Name]).

%% ws_password_input(+Name:atom) is det.
%
%  Write a password input element with the given field name.
%
%  Output:  <input type="password" name="Name" autofocus/>
ws_password_input(Name) :-
    format('<input type="password" name="~w" autofocus/>~n', [Name]).

%% ws_textarea_input(+Name:atom) is det.
%
%  Write a textarea element with the given field name.
%  Default dimensions are 5 rows by 40 columns.
%
%  Output:  <textarea name="Name" rows="5" cols="40" autofocus></textarea>
ws_textarea_input(Name) :-
    format('<textarea name="~w" rows="5" cols="40" autofocus></textarea>~n', [Name]).

%% ws_hidden_input(+Name:atom, +Value) is det.
%
%  Write a hidden input element carrying Name/Value state.
%  Value is HTML-escaped before being placed in the attribute.
%
%  Output:  <input type="hidden" name="Name" value="EscapedValue"/>
ws_hidden_input(Name, Value) :-
    html_escape(Value, SafeValue),
    format('<input type="hidden" name="~w" value="~w"/>~n', [Name, SafeValue]).

%% ws_submit(+Label:atom) is det.
%
%  Write a submit button with the given label.
%
%  Output:  <input type="submit" value="Label"/>
ws_submit(Label) :-
    format('<input type="submit" value="~w"/>~n', [Label]).
